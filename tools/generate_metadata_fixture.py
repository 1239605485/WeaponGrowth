"""Extract declaration-only test metadata from the user's IL2CPP C# dump.

No method bodies or executable code are imported. Unknown members must fail in
the native integration test rather than being invented by a permissive mock.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import zipfile

parser = argparse.ArgumentParser()
parser.add_argument('dump')
args = parser.parse_args()
types = {}
selected = {'Main', 'Player', 'Entity', 'Item', 'Projectile', 'NPC', 'Recipe',
            'Chest', 'FileData', 'PlayerFileData', 'ItemID', 'ProjectileID',
            'WhipTagEffect', 'ChatCommandProcessor', 'ChatMessage', 'ChatHelper',
            'IEntitySource', 'NewProjectileModifier', 'String', 'ProjectileKey', 'NetMessage', 'NetworkText'}


def parameters(text):
    # Attribute/default expressions can contain commas; split at depth zero.
    result, current, depth = [], '', 0
    for char in text + ',':
        if char == ',' and depth == 0:
            value = re.sub(r'\[[^\]]*\]', '', current).split('=')[0].strip()
            current = ''
            if value:
                parts = value.split()
                result.append({'type': ' '.join(parts[:-1]), 'name': parts[-1]})
        else:
            current += char
            if char in '[(<': depth += 1
            if char in '])>': depth -= 1
    return result


with zipfile.ZipFile(args.dump) as archive:
    for path in archive.namelist():
        if Path(path).stem not in selected or not path.endswith('.cs'):
            continue
        source = archive.read(path).decode('utf-8-sig')
        namespace = re.search(r'namespace ([\w.]+);', source)
        if not namespace:
            continue
        namespace = namespace[1]
        stack, pending, depth = [], None, 0
        for raw in source.splitlines():
            line = raw.strip()
            if not line or line.startswith('[') or line.startswith('//'):
                continue
            declaration = re.match(r'(?:public|private|protected|internal)\s+(?:(?:static|sealed|abstract|readonly|partial)\s+)*(?:class|struct|interface|enum)\s+(\w+)(?:\s*:\s*([^,{]+))?', line)
            delegate = re.match(r'public delegate \S+ (\w+)\(', line)
            if delegate:
                types[namespace + '.' + delegate[1]] = {'fields': {}, 'properties': {}, 'methods': [], 'base': ''}
            if declaration:
                name = (stack[-1][0] + '+' if stack else namespace + '.') + declaration[1]
                parent = declaration[2].strip() if declaration[2] else ''
                types[name] = {'fields': {}, 'properties': {}, 'methods': [], 'base': parent}
                pending = name
            elif stack and depth == stack[-1][1]:
                owner = types[stack[-1][0]]
                method = re.match(r'(?:public|private|protected|internal)\s+(?:(?:static|virtual|override|sealed|extern|unsafe|abstract)\s+)*(\S+)\s+(\w+)\((.*)\)', line)
                member = re.match(r'(?:public|private|protected|internal)\s+(?:(?:static|readonly|const|volatile)\s+)*(\S+)\s+(\w+)\s*(;|=|$)', line)
                if method:
                    owner['methods'].append({'name': method[2], 'return': method[1], 'static': 'static ' in line, 'params': parameters(method[3])})
                elif member:
                    kind = 'properties' if member[3] == '' else 'fields'
                    owner[kind][member[2]] = {'type': member[1], 'static': 'static ' in line}
            depth += line.count('{') - line.count('}')
            if pending and '{' in line:
                stack.append((pending, depth))
                pending = None
            while stack and depth < stack[-1][1]:
                stack.pop()

output = Path(__file__).resolve().parents[1] / 'tests/fixtures/game_metadata.hpp'
output.parent.mkdir(exist_ok=True)
body = json.dumps(types, ensure_ascii=False, separators=(',', ':'))
output.write_text('// Generated by tools/generate_metadata_fixture.py; declaration data only.\n'
                  '// Input SHA256: ' + hashlib.sha256(Path(args.dump).read_bytes()).hexdigest() + '\n'
                  '#pragma once\ninline constexpr const char* game_metadata_json = R"WG_META(' + body + ')WG_META";\n', encoding='utf-8')
print(f'{len(types)} types, {sum(len(t["methods"]) for t in types.values())} methods -> {output}')
