"""Generate Native value data from the supplied original Lua tables (build time only)."""
import argparse
import hashlib
import json
from pathlib import Path
from lupa import LuaRuntime

parser = argparse.ArgumentParser()
parser.add_argument('source', type=Path)
parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'src/catalog/generated.hpp')
args = parser.parse_args()
lua = LuaRuntime(unpack_returned_tuples=True)
lib = args.source / 'Resources/lib'
def load(name):
    return lua.execute((lib / (name + '.lua')).read_text(encoding='utf-8'))

catalog, sources, recipes, anchors, legacy = [load(n) for n in ('weapon_catalog','weapon_sources','weapon_recipe_origins','progression_anchors','legacy_weapon_classes')]
classes = {'melee': 1, 'ranged': 2, 'magic': 3, 'summon': 4}
stages = dict(anchors['items'].items())
stages.update(dict(recipes.items()))
names = {}
for name, entry in sources.items():
    stages[entry['id']] = entry['stage']
    names[entry['id']] = name
rows = []
for id_, entry in sorted(catalog.items()):
    rows.append(f' {{{id_},{entry["damage"]},{entry["useTime"]},{classes[entry["category"]]},{json.dumps(entry["referenceKey"])}}},')
out = ['// Generated by tools/generate_catalog.py; do not edit. Original data: user v1.8.0.', '#pragma once', '#include <cstddef>', 'namespace wg::generated {', 'struct Sample {int id,damage,use_time,category;const char* reference;};', 'inline constexpr Sample samples[]={', *rows, '};', 'struct Pair {int id,value;};', 'inline constexpr Pair anchors[]={']
out += [f' {{{int(k)},{int(v)}}},' for k,v in sorted(stages.items())]
out += ['};','inline constexpr Pair tiles[]={']
out += [f' {{{int(k)},{int(v)}}},' for k,v in sorted(anchors['tiles'].items())]
out += ['};','inline constexpr Pair legacy_classes[]={']
out += [f' {{{int(k)},{classes[v]}}},' for k,v in sorted(legacy.items())]
out += ['};','}']
args.output.write_text('\n'.join(out)+'\n',encoding='utf-8')
digest = hashlib.sha256(args.output.read_bytes()).hexdigest()
print(f'{len(rows)} samples, {len(stages)} origins; SHA256 {digest}')
